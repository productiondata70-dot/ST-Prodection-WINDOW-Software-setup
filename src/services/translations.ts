export function autoTranslateToUrdu(nameEn: string): string {
  const clean = nameEn.trim().toLowerCase();
  if (!clean) return '';
  if (productUrduDict[clean]) return productUrduDict[clean];

  // Try phrase matching
  for (const [key, val] of Object.entries(productUrduDict)) {
    if (clean === key) return val;
  }

  // Try word-by-word matching
  const words = clean.split(/[\s-]+/);
  const translatedWords = words.map(w => productUrduDict[w] || w);
  const result = translatedWords.join(' ');
  if (result !== clean) return result;

  // Basic transliteration fallbacks for common phonetic patterns
  return '';
}

